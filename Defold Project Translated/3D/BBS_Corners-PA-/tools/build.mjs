import fs from 'node:fs';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
const root=path.resolve(import.meta.dirname,'..');
const brand=JSON.parse(fs.readFileSync(path.join(root,'branding.json'),'utf8'));
const project=fs.readFileSync(path.join(root,'game.project'),'utf8');
if(!project.includes('title = '+brand.name+'\n'))throw Error('game.project title must match branding.json');
const workspace=path.resolve(root,'../../..');
const bob=process.env.DEFOLD_BOB||path.join(workspace,'.tools/bob.jar');
const bundledJava=path.join(process.env.USERPROFILE||'','Documents/Defold/packages/jdk-25.0.4.1+1/bin/java.exe');
const java=process.env.DEFOLD_JAVA||(fs.existsSync(bundledJava)?bundledJava:'java');
if(!fs.existsSync(bob))throw Error('Set DEFOLD_BOB to the Defold 1.14.0 bob.jar path. Download: https://d.defold.com/archive/d295ed4edff2e49072719835713e625f409849f1/bob/bob.jar');
const platform=process.argv.includes('--windows')?'x86_64-win32':'wasm-web';
const variant=process.argv.includes('--debug')?'debug':'release';
const result=spawnSync(java,['-jar',bob,'--platform',platform,'--architectures',platform,'--variant',variant,'--archive','build','bundle','--bundle-output',platform==='wasm-web'?'publish':'publish/windows'],{cwd:root,stdio:'inherit',windowsHide:true});
if(result.status!==0)process.exit(result.status||1);
if(platform==='wasm-web')fs.copyFileSync(path.join(root,'assets/branding/icon.png'),path.join(root,'publish',brand.name,'icon.png'));
const git=spawnSync('git',['rev-parse','HEAD'],{cwd:root,encoding:'utf8',windowsHide:true});
const build={name:brand.name,timestamp:new Date().toISOString(),platform,variant,sourceCommit:git.status===0?git.stdout.trim():'uncommitted',engine:'1.14.0',engineSha:'d295ed4edff2e49072719835713e625f409849f1'};
fs.writeFileSync(path.join(root,'publish',platform==='wasm-web'?'build-info.json':'windows/build-info.json'),JSON.stringify(build,null,2));
console.log('Local build ready: '+JSON.stringify(build));
