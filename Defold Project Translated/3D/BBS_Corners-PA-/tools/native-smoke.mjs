import fs from 'node:fs';
import path from 'node:path';
import {spawn} from 'node:child_process';
const root=path.resolve(import.meta.dirname,'..');
const brand=JSON.parse(fs.readFileSync(path.join(root,'branding.json'),'utf8'));
const folder=path.join(root,'publish/windows',brand.name);
const executable=path.join(folder,brand.executable+'.exe');
if(!fs.existsSync(executable))throw Error('Build Windows first: node tools/build.mjs --windows');
const logdir=path.join(root,'qa/artifacts/native-log');fs.mkdirSync(logdir,{recursive:true});
const child=spawn(executable,['--config=engine.run_while_iconified=1','--config=project.write_log=2','--config=project.log_dir='+logdir],{cwd:folder,windowsHide:true,stdio:['ignore','pipe','pipe']});
let output='',exited=false,exitCode=null;
child.stdout.on('data',b=>output+=b);child.stderr.on('data',b=>output+=b);
child.on('exit',code=>{exited=true;exitCode=code});
await new Promise(resolve=>setTimeout(resolve,5000));
const logfile=path.join(logdir,'log.txt');if(fs.existsSync(logfile))output+=fs.readFileSync(logfile,'utf8');
const report={timestamp:new Date().toISOString(),executable,exited,exitCode,output,passed:!exited&&!/ERROR:|stack traceback:/.test(output)&&/BBS_EVENT DISPLAYED/.test(output)};
if(!exited)child.kill();
fs.mkdirSync(path.join(root,'qa/artifacts'),{recursive:true});fs.writeFileSync(path.join(root,'qa/artifacts/native-smoke.json'),JSON.stringify(report,null,2));
console.log(report.passed?'PASS Windows release starts, loads the scene, and runs without errors.':JSON.stringify(report,null,2));
if(!report.passed)process.exitCode=1;
