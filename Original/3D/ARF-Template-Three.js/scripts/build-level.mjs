import fs from 'node:fs';
import path from 'node:path';
import {build} from 'vite';
import {finalizeHTML,writePackage} from './package-html.mjs';
import {parseFlowDocument,flowRuntime} from '../src/layout/arrowFlow.ts';
import {requireClearance} from '../src/layout/visualClearance.ts';
const [file,network='preview']=process.argv.slice(2);
if(!file)throw new Error('Usage: npm run build:level -- <level.arrow-flow.json> [al|fb|gg|is|mtg|mo|un|vu|preview]');
const profiles=JSON.parse(fs.readFileSync('src/networkProfiles.json'));
if(network!=='preview'&&!profiles.some(p=>p.tag===network))throw new Error('Unknown network');
const stat=fs.statSync(file);if(stat.size>4_000_000)throw new Error('Level JSON exceeds 4 MB');
const doc=parseFlowDocument(JSON.parse(fs.readFileSync(file,'utf8'))),runtime=flowRuntime(doc);
if(network!=='preview')requireClearance(doc);
const name=path.basename(file).replace(/[^a-z0-9_-]/gi,'-').toLowerCase();
const outDir=`dist/custom/${name}/${network}`;
await build({mode:network==='preview'?'production':network,define:{__CUSTOM_LEVEL__:JSON.stringify(runtime),__DURATION__:'90'},build:{outDir}});
const profile=profiles.find(p=>p.tag===network),{html}=finalizeHTML(fs.readFileSync(`${outDir}/index.html`,'utf8'),profile);
fs.writeFileSync(`${outDir}/index.html`,html);
const fileName=`arf_mip_grhpl_conveyor_${name}_real_nougc_noseason_en_90seconds_na_${network}.${profile?.zip?'zip':'html'}`;
const bytes=writePackage(`${outDir}/${fileName}`,html,profile);
console.log(`Custom level: ${outDir}/${fileName} (${bytes} bytes); local preview: ${outDir}/index.html`);
